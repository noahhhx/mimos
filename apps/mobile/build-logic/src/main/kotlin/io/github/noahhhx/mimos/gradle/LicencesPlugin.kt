package io.github.noahhhx.mimos.gradle

import org.gradle.api.DefaultTask
import org.gradle.api.Plugin
import org.gradle.api.Project
import org.gradle.api.artifacts.component.ModuleComponentIdentifier
import org.gradle.api.artifacts.result.ResolvedArtifactResult
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import org.gradle.maven.MavenModule
import org.gradle.maven.MavenPomArtifact

const val GENERATE_LICENCES = "generateLicences"

/**
 * Registers [GENERATE_LICENCES], which writes the licences of everything in
 * [RELEASE_RUNTIME_CLASSPATH] as a Kotlin list, read from each module's POM (or its parents'), so
 * the app's Licences can never miss a dependency or name one it no longer has.
 * [GenerateLicences.extra] adds what Maven does not ship, such as fonts. The module adds the output
 * directory to its sources.
 */
class LicencesPlugin : Plugin<Project> {
    override fun apply(project: Project) {
        project.tasks.register(GENERATE_LICENCES, GenerateLicences::class.java) {
            group = "build"
            description = "Writes the licences of the app's release dependencies."
            dependencies.set(project.provider { collectNotices(project) })
            outputDir.convention(project.layout.buildDirectory.dir("generated/licences"))
        }
    }
}

@CacheableTask
abstract class GenerateLicences : DefaultTask() {
    @get:Input abstract val dependencies: ListProperty<Notice>

    @get:Input abstract val extra: ListProperty<Notice>

    @get:Input abstract val packageName: Property<String>

    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val notices = (dependencies.get() + extra.get()).sortedBy { it.name.lowercase() }
        val dir = outputDir.get().asFile
        dir.deleteRecursively()
        val target = dir.resolve(packageName.get().replace('.', '/')).resolve("Licences.kt")
        target.parentFile.mkdirs()
        target.writeText(licencesSource(packageName.get(), notices))
    }
}

internal fun licencesSource(packageName: String, notices: List<Notice>): String {
    fun literal(text: String) =
        "\"" + text.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
    val rows =
        notices.joinToString("\n") { notice ->
            "        OpenSource(${literal(notice.name)}, " +
                "${literal(notice.versions.joinToString(", "))}, " +
                "listOf(${notice.licences.joinToString(", ") { literal(it) }})),"
        }
    return "package $packageName\n\n" +
        "import io.github.noahhhx.mimos.settings.OpenSource\n\n" +
        "/** Generated by the $GENERATE_LICENCES task from the release dependencies' POMs. */\n" +
        "internal val LICENCES: List<OpenSource> =\n    listOf(\n$rows\n    )\n"
}

private fun collectNotices(project: Project): List<Notice> {
    val root =
        project.configurations.getByName(RELEASE_RUNTIME_CLASSPATH).incoming.resolutionResult.root
    val modules = reachableModules(root).map { Coordinates(it.group, it.module, it.version) }
    val poms = mutableMapOf<Coordinates, Pom?>()
    fun fetch(wanted: Collection<Coordinates>) {
        val missing = wanted.filter { it !in poms }
        if (missing.isEmpty()) return
        val query = project.dependencies.createArtifactResolutionQuery()
        missing.forEach { query.forModule(it.group, it.name, it.version) }
        val found =
            query.withArtifacts(MavenModule::class.java, MavenPomArtifact::class.java).execute()
        for (component in found.resolvedComponents) {
            val id = component.id as? ModuleComponentIdentifier
            val file =
                component
                    .getArtifacts(MavenPomArtifact::class.java)
                    .filterIsInstance<ResolvedArtifactResult>()
                    .firstOrNull()
                    ?.file
            if (id != null)
                poms[Coordinates(id.group, id.module, id.version)] = file?.let(::readPom)
        }
        missing.forEach { poms.putIfAbsent(it, null) }
    }
    fetch(modules)
    // A POM without licences inherits its parent's; parents come a generation at a time.
    var generation = modules
    while (generation.isNotEmpty()) {
        val parents = generation.mapNotNull {
            poms[it]?.takeIf { pom -> pom.licences.isEmpty() }?.parent
        }
        fetch(parents)
        generation = parents.filter { poms[it] != null }.distinct()
    }
    fun licencesOf(coordinates: Coordinates): List<String> {
        val pom = poms[coordinates] ?: return emptyList()
        return pom.licences.ifEmpty { pom.parent?.let(::licencesOf).orEmpty() }
    }
    return notices(modules.associateWith(::licencesOf))
}
